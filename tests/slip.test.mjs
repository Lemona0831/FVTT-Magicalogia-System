import assert from "node:assert/strict";
import { areaOf, slipImage } from "../module/sheet-v3/slip.js";
assert.equal(areaOf("별 2 어둠 x"), "Darkness");
assert.equal(areaOf("별 2"), "Star");
assert.equal(areaOf("전 x"), "All");
assert.equal(areaOf("전체 3"), "All");
assert.equal(areaOf("없음"), "All");
assert.equal(areaOf(""), "All");
assert.equal(areaOf("꿈 1"), "Dream");
assert.ok(slipImage("Star", 3).endsWith("Star-03.png"));
assert.ok(slipImage("Star", 0).endsWith("Star-0.png"));
assert.ok(slipImage("Star", 12).endsWith("Star-08.png"));
assert.ok(slipImage("Star", "x").endsWith("Star-0.png"));
console.log("slip ok");
